#!/usr/bin/env node
/**
 * apply-llm-audit.mjs — Generates a migration that applies LLM-audit fixes
 *
 * Reads the JSON output of llm-audit-program.mjs and generates a single
 * SQL migration that does targeted text replacements per finding. Only
 * applies HIGH and MEDIUM severity by default; LOW are skipped (set
 * --include-low to apply them too).
 *
 * USAGE:
 *   node scripts/llm-audit-program.mjs --all --json=/tmp/llm-findings.json
 *   node scripts/apply-llm-audit.mjs --input=/tmp/llm-findings.json
 *   supabase db query --linked --file <generated-migration>
 *
 * Each finding becomes one UPDATE statement with a `replace()` call on
 * the affected field. Text fields use replace() directly; JSONB fields
 * cast through ::text and back. ASCII-only.
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'

function parseArgs() {
  const args = { input: null, includeLow: false }
  for (const a of process.argv.slice(2)) {
    if (a === '--include-low') args.includeLow = true
    else if (a.startsWith('--input=')) args.input = a.slice('--input='.length)
  }
  if (!args.input) {
    console.error('Usage: apply-llm-audit.mjs --input=<json> [--include-low]')
    process.exit(1)
  }
  return args
}

function asciiize(s) {
  if (!s) return s
  return s
    .replace(/[–—]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/…/g, '...')
    .replace(/ /g, ' ')
}

function escapeSql(s) {
  return s.replace(/'/g, "''")
}

const TEXT_FIELDS = new Set(['intro', 'how_to_spend', 'sweet_spots', 'quirks', 'lounge_access', 'award_chart'])
const JSONB_FIELDS = new Set(['transfer_partners', 'tier_benefits', 'member_programs'])

function buildUpdate(slug, finding) {
  const field = finding.field
  const claim = asciiize(finding.claim)
  const fix = asciiize(finding.suggested_fix)
  if (!claim || !fix || claim === fix) return null
  if (!TEXT_FIELDS.has(field) && !JSONB_FIELDS.has(field)) return null
  if (TEXT_FIELDS.has(field)) {
    return `update programs set ${field} = replace(${field}, '${escapeSql(claim)}', '${escapeSql(fix)}'), last_verified = current_date where slug = '${slug}' and ${field} like '%${escapeSql(claim)}%';`
  }
  // JSONB field — cast text in/out
  return `update programs set ${field} = replace(${field}::text, '${escapeSql(claim)}', '${escapeSql(fix)}')::jsonb, last_verified = current_date where slug = '${slug}' and ${field}::text like '%${escapeSql(claim)}%';`
}

function nextMigrationNumber() {
  const files = readdirSync('supabase/migrations').filter((f) => /^\d{3}_/.test(f))
  const max = files.map((f) => parseInt(f.slice(0, 3), 10)).filter((n) => !Number.isNaN(n)).reduce((a, b) => Math.max(a, b), 0)
  return String(max + 1).padStart(3, '0')
}

function main() {
  const args = parseArgs()
  const programs = JSON.parse(readFileSync(args.input, 'utf8'))

  let totalApplied = 0
  let totalSkipped = 0
  const sections = []

  for (const p of programs) {
    if (!p.findings?.length) continue
    const stmts = []
    for (const f of p.findings) {
      const sev = (f.severity ?? '').toLowerCase()
      if (!args.includeLow && sev === 'low') {
        totalSkipped++
        continue
      }
      const stmt = buildUpdate(p.slug, f)
      if (stmt) {
        stmts.push(`-- [${sev.toUpperCase()}] ${f.field}: ${f.issue}\n${stmt}`)
        totalApplied++
      } else {
        totalSkipped++
      }
    }
    if (stmts.length) {
      sections.push(`-- ============================================================\n-- ${p.slug}\n-- ============================================================\n\n${stmts.join('\n\n')}`)
    }
  }

  if (!sections.length) {
    console.log('No applicable fixes (all LOW severity or no usable findings).')
    process.exit(0)
  }

  const num = nextMigrationNumber()
  const fname = `supabase/migrations/${num}_apply_llm_audit_fixes.sql`
  const sql = `-- Auto-generated by scripts/apply-llm-audit.mjs from ${args.input}
-- Applies HIGH/MEDIUM-severity LLM audit findings as targeted text replacements.
-- Each UPDATE is conditional on the matching string still being present, so
-- re-applying after manual edits is safe (becomes a no-op).
-- ASCII-only per feedback_ascii_only_in_sql_data.md.

${sections.join('\n\n')}
`
  writeFileSync(fname, sql)
  console.log(`Wrote ${fname}`)
  console.log(`  applied: ${totalApplied}, skipped: ${totalSkipped}`)
  console.log(`Apply with: supabase db query --linked --file ${fname}`)
}

main()
